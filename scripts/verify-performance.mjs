import { spawn } from 'node:child_process';
import path from 'node:path';
import { ROOT, useLocalTempDir } from './lib/local-temp.mjs';
import { electronExecutable } from './lib/electron-runtime.mjs';
useLocalTempDir('performance');
const seconds = Number(process.env.WCS_PERF_SECONDS || '20');
if (!Number.isInteger(seconds) || seconds < 3 || seconds > 3600) throw new Error('WCS_PERF_SECONDS 必须为 3–3600 的整数秒');
const env = { ...process.env, WCS_PERF_PROBE: '1', WCS_PERF_SECONDS: process.env.WCS_PERF_SECONDS || '20', WCS_USER_DATA: path.join(ROOT, '.tmp', 'performance', 'user-data') };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(electronExecutable(), ['--no-sandbox', ROOT], { env, cwd: ROOT, windowsHide: true, stdio: 'inherit' });
const timer = setTimeout(() => { child.kill(); process.exitCode = 1; }, Math.max(120_000, seconds * 1000 + 60_000));
child.once('error', error => { clearTimeout(timer); console.error(error); process.exitCode = 1; });
child.once('exit', code => { clearTimeout(timer); process.exitCode = code ?? 1; });
